# Ударения для голоса Дмитрий (edge-tts, ru-RU-DmitryNeural).
# ПРОВЕРЕНО 23.11 (v9 -> v11): знак ударения U+0301 ЛОМАЕТ слова у этого голоса:
#   окупа́емость -> «окупаЁмость», хинка́ли/чебуре́ки/до́неры/хачапу́ри -> не тот слог, сети́ -> всё равно «се́ти».
# Поэтому знаки НЕ ставим. Голос без знаков читает эти слова верно (v7 принят Валом на слух).
# Слова, где голос ошибается, не «лечим» знаком, а меняем фразу (см. AVOID).
import re
# Единственное исключение, проверенное фонемной моделью: «бо́льших» со знаком звучит верно, без знака «больши́х».
STRESS = {'больших': 'бо́льших'}
# Слова-омографы: голос ставит ударение не туда. Переписать фразу без них.
AVOID = {
    'сыром': 'голос читает «сыро́м»; писать «шпинат и сыр»',
    'сети': 'дательный «к нашей се́ти» по норме, но на слух режет; писать «присоединяйся к нам»',
}
# Проверено фонемами (23.11): «хлеба и зрелищ» голос читает «хле́ба» верно.
def apply_stress(text):
    def rep(m):
        w = m.group(0); low = w.lower()
        if low in STRESS and '́' not in w:
            r = STRESS[low]; return r[0].upper() + r[1:] if w[0].isupper() else r
        return w
    return re.sub(r'[А-Яа-яЁё]+', rep, text)
def check(text):
    """Возвращает список проблем: лишние знаки ударения и слова из AVOID."""
    bad = []
    for w in re.findall(r'[А-Яа-яЁё́]+', text):
        low = w.lower()
        if '́' in w and low not in STRESS.values(): bad.append(f'знак ударения в «{w}» запрещён')
        if low.replace('́', '') in AVOID: bad.append(f'«{w}»: {AVOID[low.replace(chr(0x301), "")]}')
    return bad
