# Словарь ударений для голоса Дмитрий (edge-tts). Применяется к тексту перед озвучкой автоматически.
# Пополнять каждый раз, когда Вал поймал неверное ударение. Знак ударения: U+0301 после гласной.
import re
STRESS = {
    'сыром': 'сы́ром', 'сыра': 'сы́ра', 'сети': 'сети́', 'больших': 'бо́льших',
    'кажуал': 'ка́жуал', 'хинкали': 'хинка́ли', 'чебуреки': 'чебуре́ки', 'чебурек': 'чебуре́к',
    'сулугуни': 'сулугу́ни', 'хачапури': 'хачапу́ри', 'донеры': 'до́неры', 'паушального': 'паушально́го',
    'роялти': 'роя́лти', 'франчайзи': 'франча́йзи', 'джигит': 'джиги́т', 'окупаемость': 'окупа́емость',
}
def apply_stress(text):
    def rep(m):
        w = m.group(0); low = w.lower()
        if low in STRESS and '́' not in w:
            r = STRESS[low]; return r[0].upper() + r[1:] if w[0].isupper() else r
        return w
    return re.sub(r'[А-Яа-яЁё]+', rep, text)
